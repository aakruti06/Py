''' Assignment operator '''


a = 5
b = 10
c = 15
print("a = {}, b = {}, c = {}".format(a,b,c))
print("--------------")
print()

'''  add and assign   =+   '''
print("   += - op")
a+=10
print("a = {}".format(a))
print("--------------")
print()

''' subtract and assign   -=  '''
print("   -= - op")
b-=2
print("b = {}".format(b))
print("--------------")
print()

''' multiply and assign   *= '''
print("   *= - op")
c*=2
print("c = {}".format(c))
print("--------------")
print()

'''  divide and assign /=  '''
print("   /= - op")
a/=2
print("a = {}".format(a))
print("--------------")
print()

'''   modulus and assign %= '''
print("   %= - op")
b%=2
print("b = {}".format(b))
print("--------------")
print()

'''  exponentiate and assign **= '''
print("   **= - op")
c**=2
print("c = {}".format(c))
print("---------------")
print()

'''  floor division and assign //=  '''
print("   //= - op")
a//=1
print("a = {}".format(a))
print("---------------")
print()
