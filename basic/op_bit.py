''' bitwise operators '''

a = 5
b = 10
c = 15
print("a={},b={},c={}".format(a,b,c))
print()

''' AND operator -  &'''
print("    & op")
print("a&b = {}".format(a&b))
print("a&c = {}".format(a&c))
print("b&c = {}".format(b&c))
print("------------")
print()

''' OR operator  -  |'''
print("    | op")
print("a|b = {}".format(a|b))
print("a|C = {}".format(a|c))
print("b|C = {}".format(b|c))
print("------------")
print()

''' NOT operator   - ~'''
print("    ~ op")
print("~a = {}".format(~a))
print("~b = {}".format(~b))
print("~c = {}".format(~c))
print("------------")
print()

''' XOR operator -  ^ '''
print("    ^ op")
print("a^b = {}".format(a^b))
print("a^c = {}".format(a^c))
print("b^c = {}".format(b^c))
print("------------")
print()

''' Right shift -  >>'''
print("    >> op")
print("a>>2 = {}".format(a>>2))
print("b>>1 = {}".format(b>>1))
print("c>>3 = {}".format(c>>3))
print("------------")
print("a={},b={},c={}".format(a,b,c))
print()

'''  Left shift   -  <<'''
print("    << op")
print("a<<1 = {}".format(a<<1))
print("b<<2 = {}".format(b<<2))
print("c<<1 = {}".format(c<<1))
print("------------")
print("a={},b={},c={}".format(a,b,c))
print()


